// Regenerates every QRGUARD brand asset from marks.mjs.
//   node brand/render.mjs            (from the repo root, after `npm ci` in e2e/)
// Uses the E2E suite's playwright-core and a Chromium binary (CHROMIUM_PATH, as in e2e/run.sh).
import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { PALETTE, mark, markBody, monoBody, monoMark, placed } from './marks.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const { chromium } = createRequire(path.join(ROOT, 'e2e/package.json'))('playwright-core')

const svgFiles = {
  'brand/qrguard-mark.svg': mark(),
  'brand/qrguard-mark-mono.svg': monoMark(PALETTE.ink),
  'web/public/qrguard-mark.svg': mark(),
  'web/public/favicon.svg': mark({ detail: false }),
  'mobile/src/constants/brandMark.ts':
    '// Generated by brand/render.mjs from brand/marks.mjs. Do not edit by hand.\n' +
    `export const BRAND_MARK_SVG = ${JSON.stringify(mark().trim())}\n`,
}

const app = (scale) => placed(markBody(), { scale, background: PALETTE.iconBackground })
const pngFiles = [
  ['web/public/apple-touch-icon.png', 180, app(0.72)],
  ['web/public/favicon-32.png', 32, placed(markBody({ detail: false }), { scale: 0.96 })],
  ['mobile/assets/icon.png', 1024, app(0.72)],
  ['mobile/assets/android-icon-foreground.png', 1024, placed(markBody(), { scale: 0.6 })],
  ['mobile/assets/android-icon-background.png', 1024, placed('', { scale: 1, background: PALETTE.iconBackground })],
  ['mobile/assets/android-icon-monochrome.png', 1024, placed(monoBody(), { scale: 0.6 })],
  ['mobile/assets/splash-icon.png', 1024, placed(markBody(), { scale: 0.9 })],
  ['mobile/assets/favicon.png', 48, placed(markBody({ detail: false }), { scale: 0.96 })],
]

for (const [file, content] of Object.entries(svgFiles)) fs.writeFileSync(path.join(ROOT, file), content)

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined })
try {
  for (const [file, size, source] of pngFiles) {
    const page = await browser.newPage({ viewport: { width: size, height: size } })
    const src = 'data:image/svg+xml;base64,' + Buffer.from(source).toString('base64')
    await page.setContent(`<style>*{margin:0}</style><img src="${src}" width="${size}" height="${size}">`)
    await page.locator('img').evaluate((img) => img.decode())
    await page.screenshot({ path: path.join(ROOT, file), omitBackground: true })
    await page.close()
  }
} finally {
  await browser.close()
}
console.log(`wrote ${Object.keys(svgFiles).length} vector files and ${pngFiles.length} PNG files`)
